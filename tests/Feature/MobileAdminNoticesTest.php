/** Actual HTTP routes; all new DDL/FKs and delivery rows remain strictly TEMP. */
class MobileAdminNoticesTest extends TestCase
{
    private $db; private $grammar;
    private Tenant $tenant; private Tenant $foreign;
    private array $actors = [], $tokens = [], $members = [];
    private string $base;

    protected function setUp(): void
    {
        parent::setUp();
        if (getenv('CLUBUNIO_TEST_DB') !== '1') $this->markTestSkipped('Explicit synthetic rolled-back PG only');
        config(['clubunio-mobile.enabled' => true, 'clubunio-mobile.native_push_admin_enabled' => true,
            'clubunio-mobile-push.enabled' => false, 'clubunio-mobile-push.delivery_enabled' => false,
            'cache.default' => 'array', 'hashing.bcrypt.rounds' => 4]);
        Http::preventStrayRequests(); Mail::fake();
        $this->db = DB::connection('clubunio');
        $this->assertSame('db_acdf8d_dclubora', $this->db->getDatabaseName());
        $this->db->beginTransaction();
        $this->db->statement("SET LOCAL application_name TO 'clubunio-admin-notices-1000-test'");
        $this->tenant = Tenant::create(['slug' => 'notice-'.bin2hex(random_bytes(6)), 'name' => 'Synthetic club']);
        $this->foreign = Tenant::create(['slug' => 'notice-foreign-'.bin2hex(random_bytes(6)), 'name' => 'Synthetic foreign']);
        foreach (['admin','office','trainer','technical_lead','member','parent'] as $key) {
            $actor = new Account;
            $actor->forceFill(['username' => 'notice-'.bin2hex(random_bytes(8)), 'display_name' => 'Synthetic '.$key,
                'active' => true, 'api_only' => false, 'password' => bcrypt('fixture')])->save();
            $this->actors[$key] = $actor;
            $this->db->table('clubora.tenant_accounts')->insert(['tenant_id' => $this->tenant->id, 'account_id' => $actor->id,
                'role' => $key === 'parent' ? 'member' : $key, 'portal_enabled' => true]);
            $member = $this->db->table('clubora.members')->insertGetId(['tenant_id' => $this->tenant->id,
                'first_name' => 'Synthetic', 'last_name' => $key, 'birth_date' => $key === 'member' ? now()->subYears(12)->toDateString() : '1980-01-01']);
            $this->members[$key] = $member;
            $this->db->table('clubora.account_member_links')->insert(['tenant_id' => $this->tenant->id,
                'account_id' => $actor->id, 'member_id' => $member, 'kind' => 'self', 'state' => 'approved', 'source' => 'synthetic-test']);
            $this->tokens[$key] = $this->postJson('/api/mobile/v1/session', ['username' => $actor->username,
                'password' => 'fixture', 'device_name' => 'Synthetic notice'])->assertOk()->json('data.token');
        }
        $this->db->table('clubora.account_member_links')->insert(['tenant_id' => $this->tenant->id,
            'account_id' => $this->actors['parent']->id, 'member_id' => $this->members['member'],
            'kind' => 'parent', 'state' => 'approved', 'source' => 'synthetic-test']);
        $this->db->table('clubora.tenant_accounts')->insert(['tenant_id' => $this->foreign->id,
            'account_id' => $this->actors['admin']->id, 'role' => 'admin', 'portal_enabled' => true]);
        $this->db->statement('CREATE TEMP TABLE notice_parent_tenants(id bigint PRIMARY KEY)');
        $this->db->statement('CREATE TEMP TABLE notice_parent_accounts(tenant_id bigint,account_id bigint,PRIMARY KEY(tenant_id,account_id))');
        foreach ([$this->tenant, $this->foreign] as $tenant) $this->db->table('pg_temp.notice_parent_tenants')->insert(['id' => $tenant->id]);
        foreach ($this->actors as $actor) $this->db->table('pg_temp.notice_parent_accounts')->insert(['tenant_id' => $this->tenant->id, 'account_id' => $actor->id]);
        $this->db->table('pg_temp.notice_parent_accounts')->insert(['tenant_id' => $this->foreign->id, 'account_id' => $this->actors['admin']->id]);
        foreach (['mobile_push_outbox','mobile_push_devices','mobile_push_bindings'] as $table) {
            // LIKE copies local checks/indexes, deliberately never live foreign keys.
            $this->db->statement("CREATE TEMP TABLE $table (LIKE clubora.$table INCLUDING ALL)");
        }
        $this->db->unprepared('CREATE TEMP TABLE mobile_inbox (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tenant_id bigint NOT NULL,account_id bigint NOT NULL,event_key varchar(160) NOT NULL,kind varchar(30) NOT NULL,
            object_id bigint NOT NULL,read_at timestamptz,created_at timestamptz NOT NULL,
            UNIQUE(tenant_id,account_id,event_key))');
        $this->db->unprepared('CREATE TEMP TABLE mobile_app_announcements(id bigint PRIMARY KEY,tenant_id bigint NOT NULL,
            active boolean NOT NULL,starts_at timestamptz NOT NULL,ends_at timestamptz NOT NULL)');
        $queries = $this->db->pretend(fn () => (require database_path('clubunio/2026_11_04_001000_mobile_admin_notices.php'))->up());
        $sql = str_replace(['CREATE TABLE clubora.mobile_admin_', 'clubora.mobile_admin_', 'clubora.mobile_push_outbox',
            'REFERENCES clubora.tenants', 'REFERENCES clubora.tenant_accounts'],
            ['CREATE TEMP TABLE mobile_admin_', 'pg_temp.mobile_admin_', 'pg_temp.mobile_push_outbox',
            'REFERENCES pg_temp.notice_parent_tenants', 'REFERENCES pg_temp.notice_parent_accounts'], $queries[0]['query']);
        $this->db->unprepared($sql);
        $this->grammar = $this->db->getQueryGrammar();
        $this->db->setQueryGrammar(new class($this->db) extends \Illuminate\Database\Query\Grammars\PostgresGrammar {
            private function remap($table) { return str_replace(['clubora.mobile_admin_', 'clubora.mobile_push_outbox',
                'clubora.mobile_push_bindings', 'clubora.mobile_push_devices', 'clubora.mobile_inbox', 'clubora.mobile_app_announcements'],
                ['pg_temp.mobile_admin_', 'pg_temp.mobile_push_outbox', 'pg_temp.mobile_push_bindings', 'pg_temp.mobile_push_devices', 'pg_temp.mobile_inbox', 'pg_temp.mobile_app_announcements'], $table); }
            public function wrapTable($table, $prefix = null) { return parent::wrapTable($this->remap($table), $prefix); }
            public function wrap($value, $prefixAlias = false) { return parent::wrap(is_string($value) ? $this->remap($value) : $value, $prefixAlias); }
        });
        $this->base = '/api/mobile/v1/clubs/'.$this->tenant->id;
        $this->withToken($this->tokens['admin']);
    }

    protected function tearDown(): void
    {
        if (isset($this->db)) { if ($this->grammar) $this->db->setQueryGrammar($this->grammar); $this->db->rollBack(); }
        parent::tearDown();
    }
    private function payload(string $type = 'all', ?string $value = null): array
    {
        return ['target_type' => $type, 'target_value' => $value, 'title' => 'Private synthetic title', 'body' => 'Private synthetic body'];
    }
    private function command(array $payload): array
    {
        $preview = $this->postJson($this->base.'/push-admin/preview', $payload)->assertOk()->json('data');
        return $payload + ['request_key' => (string) Str::uuid(), 'revision' => $preview['revision'], 'confirm' => true];
    }
    private function send(array $command): array
    {
        return $this->postJson($this->base.'/push-admin/notices', $command)->assertOk()->json('data');
    }
    public function test_original_audiences_lookup_and_roles_are_derived_from_current_personal_memberships(): void
    {
        config(['clubunio-mobile.bootstrap.enabled'=>true]);
        $this->assertTrue(app(\App\ClubUnio\Mobile\MobileBootstrapState::class)->personalState($this->actors['admin'],$this->tenant)['pushAdminAvailable']);
        $this->assertFalse(app(\App\ClubUnio\Mobile\MobileBootstrapState::class)->personalState($this->actors['trainer'],$this->tenant)['pushAdminAvailable']);
        config(['clubunio-mobile.native_push_admin_enabled'=>false]);
        $this->assertFalse(app(\App\ClubUnio\Mobile\MobileBootstrapState::class)->personalState($this->actors['admin'],$this->tenant)['pushAdminAvailable']);
        config(['clubunio-mobile.native_push_admin_enabled'=>true]);
        config(['clubunio-mobile.bootstrap.enabled'=>false]);
        $this->getJson($this->base.'/push-admin/options')->assertOk()->assertJsonPath('data.canSend', true)
            ->assertJsonPath('data.tenantId', (int) $this->tenant->id)->assertJsonCount(5, 'data.roles');
        foreach ([['all',null,6],['office',null,1],['trainer_office',null,2],['role','technical_lead',1],
            ['account',(string) $this->actors['trainer']->id,1],['member',(string) $this->members['member'],2]] as [$type,$value,$count]) {
            $this->postJson($this->base.'/push-admin/preview', $this->payload($type,$value))->assertOk()->assertJsonPath('data.recipientCount',$count);
        }
        $this->getJson($this->base.'/push-admin/lookup?type=account&q=trainer')->assertOk()->assertJsonCount(1,'data.rows')
            ->assertJsonPath('data.rows.0.value',(string) $this->actors['trainer']->id);
        $this->getJson($this->base.'/push-admin/lookup?type=member&q=member')->assertOk()->assertJsonCount(1,'data.rows')
            ->assertJsonMissingPath('data.rows.0.email');
        $this->postJson($this->base.'/push-admin/preview',$this->payload('role','-1'))->assertUnprocessable();
        $this->withToken($this->tokens['trainer'])->getJson($this->base.'/push-admin/options')->assertForbidden();
        $this->withToken($this->tokens['office'])->getJson($this->base.'/push-admin/options')->assertOk();
        Http::assertNothingSent(); Mail::assertNothingSent();
    }
    public function test_source_is_encrypted_exact_replay_is_idempotent_and_content_requires_snapshot_and_fresh_scope(): void
    {
        $command = $this->command($this->payload('member',(string) $this->members['member']));
        $receipt = $this->send($command); $id = $receipt['noticeId'];
        $this->assertSame('disabled',$receipt['state']); $this->assertSame(2,$receipt['recipientCount']);
        $this->assertSame($id,$this->send($command)['noticeId']);
        $this->assertSame(1,$this->db->table('clubora.mobile_admin_notices')->count());
        $this->assertSame(2,$this->db->table('clubora.mobile_inbox')->count());
        $this->postJson($this->base.'/push-admin/notices',array_replace($command,['body'=>'Changed']))->assertConflict();
        $source = $this->db->table('clubora.mobile_admin_notices')->first();
        $this->assertStringNotContainsString('Private',$source->title_encrypted);
        $this->assertSame($command['body'],Crypt::decryptString($source->body_encrypted));
        $this->assertSame(hash('sha256',json_encode(array_values([$this->actors['member']->id,$this->actors['parent']->id]))),$source->recipient_sha256);
        $this->withToken($this->tokens['parent'])->getJson($this->base.'/admin-notices/'.$id)->assertOk()
            ->assertJsonPath('data.body',$command['body'])->assertHeader('Cache-Control','no-store, private');
        $this->getJson($this->base.'/push-admin/notices/'.$id)->assertForbidden();
        $this->withToken($this->tokens['office'])->getJson($this->base.'/push-admin/notices/'.$id)->assertNotFound();
        $this->getJson($this->base.'/admin-notices/'.$id)->assertNotFound();
        $this->db->table('clubora.account_member_links')->where('account_id',$this->actors['parent']->id)->where('kind','parent')->update(['state'=>'revoked']);
        $this->withToken($this->tokens['parent'])->getJson($this->base.'/admin-notices/'.$id)->assertNotFound();
        $this->withToken($this->tokens['admin'])->getJson('/api/mobile/v1/clubs/'.$this->foreign->id.'/admin-notices/'.$id)->assertNotFound();
        Http::assertNothingSent();
    }
    public function test_preview_rejects_changed_audience_and_flags_revoked_senders_and_profile_accounts_close_safely(): void
    {
        $command = $this->command($this->payload('role','trainer'));
        $this->db->table('clubora.tenant_accounts')->where('tenant_id',$this->tenant->id)->where('account_id',$this->actors['trainer']->id)->update(['role'=>'member','revision'=>2]);
        $this->postJson($this->base.'/push-admin/notices',$command)->assertConflict();
        $this->assertSame(0,$this->db->table('clubora.mobile_admin_notices')->count());
        $receipt = $this->send($this->command($this->payload()));
        $this->db->table('clubora.tenant_accounts')->where('tenant_id',$this->tenant->id)->where('account_id',$this->actors['admin']->id)->update(['role'=>'member']);
        $this->assertFalse(app(MobileAdminNoticeAccess::class)->publicationCurrent($this->tenant,$receipt['noticeId']));
        $this->assertSame(0,app(MobileAdminNoticeService::class)->publish($this->tenant,$receipt['noticeId']));
        $this->getJson($this->base.'/push-admin/notices/'.$receipt['noticeId'])->assertForbidden();
        $profile = $this->db->table('clubora.access_profiles')->insertGetId(['tenant_id'=>$this->tenant->id,'name'=>'Synthetic notice profile','permissions'=>'[]']);
        $this->db->table('clubora.tenant_accounts')->where('tenant_id',$this->tenant->id)->where('account_id',$this->actors['admin']->id)->update(['role'=>'profile','access_profile_id'=>$profile,'portal_enabled'=>false]);
        $this->getJson($this->base.'/push-admin/options')->assertForbidden();
        $this->withToken($this->tokens['office']); config(['clubunio-mobile.native_push_admin_enabled'=>false]);
        $this->getJson($this->base.'/push-admin/options')->assertStatus(503);
        $this->getJson($this->base.'/admin-notices/'.$receipt['noticeId'])->assertStatus(503);
        $this->assertSame(0,app(MobileAdminNoticeService::class)->pending());
    }
    public function test_queue_only_targets_existing_authorized_devices_and_composite_foreign_keys_reject_cross_tenant_rows(): void
    {
        $actor = $this->actors['member']; $session = explode('.',$this->tokens['member'])[0];
        foreach ([null,$this->foreign->id] as $fixed) {
            $device = (string) Str::uuid(); $binding = (string) Str::uuid();
            $this->db->table('clubora.mobile_push_devices')->insert(['id'=>$device,'proof_hash'=>hash('sha256',$device),
                'app_id'=>'synthetic.app','platform'=>'android','origin'=>'https://synthetic.example','fixed_tenant_id'=>$fixed,
                'token_cipher'=>Crypt::encryptString('synthetic-token'),'token_hash'=>hash('sha256',$binding)]);
            $this->db->table('clubora.mobile_push_bindings')->insert(['id'=>$binding,'device_id'=>$device,'account_id'=>$actor->id,
                'session_id'=>$session,'created_at'=>now()->subHour()->toIso8601String()]);
        }
        config(['clubunio-mobile-push.enabled'=>true]);
        $command = $this->command($this->payload('account',(string)$actor->id));
        $receipt = $this->send($command);
        $this->assertSame('queued',$receipt['state']); $this->assertSame(1,$receipt['deviceCount']);
        $this->send($command); app(MobileAdminNoticeService::class)->pending();
        $this->assertSame(1,$this->db->table('clubora.mobile_push_outbox')->count());
        $this->assertTrue(app(MobilePushOutbox::class)->targetAllowed($actor,$this->tenant,'admin_notice',$receipt['noticeId']));
        $this->assertFalse(app(MobilePushOutbox::class)->deliverOne());
        Http::assertNothingSent(); Mail::assertNothingSent();
        $this->expectException(\Illuminate\Database\QueryException::class);
        $this->db->transaction(fn()=>$this->db->table('clubora.mobile_admin_notice_recipients')->insert([
            'tenant_id'=>$this->foreign->id,'notice_id'=>$receipt['noticeId'],'account_id'=>$this->actors['admin']->id]));
    }
